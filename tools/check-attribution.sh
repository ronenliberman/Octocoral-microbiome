#!/usr/bin/env bash
# Fails if anything credits an AI tool. Used by two callers, so that the rule is
# defined once and cannot drift between them:
#
#   .github/workflows/no-ai-attribution.yml   on every pull request, the gate
#   .githooks/pre-push                        locally, before anything is pushed
#
# Usage: check-attribution.sh <branch-name> [<commit-range>]
#        Extra text (a pull request title and body) may be piped in on stdin.
#
# See section 1 of AGENTS.md.

set -uo pipefail

BRANCH="${1:-}"
RANGE="${2:-}"

PATTERN='anthropic|claude|copilot|codex|chatgpt|gpt-?[0-9]|cursor|gemini|llm|large language model|generated with|generated by|ai-generated|ai generated|ai-assisted|ai assisted|written by an ai|with the help of ai|co-authored-by:[^\n]*(bot|ai)\b'

# Three configuration paths in this repository have tool names in them, so
# naming those paths is legitimate. Remove the filenames before matching. A bare
# tool name outside a filename still fails, which is the intended behavior.
scrub() {
  sed -E 's#(\.github/)?copilot-instructions\.md##gI; s#\bCLAUDE\.md\b##gI; s#\.claude/?##gI'
}

fail=0
report() {
  if [ -n "${GITHUB_ACTIONS:-}" ]; then echo "::error::$1"; else echo "BLOCKED: $1"; fi
  fail=1
}

if [ -n "$BRANCH" ]; then
  if printf '%s' "$BRANCH" | scrub | grep -Eiq "$PATTERN|^(bot|ai)/"; then
    report "Branch name '$BRANCH' names an AI tool. Rename it before pushing, because GitHub cannot change a pull request's branch name once the pull request exists. Run: git branch -m $BRANCH yourname/topic"
  fi
fi

if [ -n "$RANGE" ]; then
  if git log --format='%s%n%b%n%(trailers)' "$RANGE" 2>/dev/null | scrub | grep -Eiq "$PATTERN"; then
    echo "Offending commits:"
    git log --format='%H %s' "$RANGE" 2>/dev/null | while read -r sha subject; do
      if git log -1 --format='%s%n%b%n%(trailers)' "$sha" | scrub | grep -Eiq "$PATTERN"; then
        echo "  ${sha:0:8} $subject"
      fi
    done
    report "A commit message credits an AI tool or carries an AI co-author trailer. Rewrite the messages and try again."
  fi

  # The rule files legitimately discuss these terms, so they are exempt.
  ADDED=$(git diff "$RANGE" --unified=0 \
    -- '*.qmd' '*.Rmd' '*.R' '*.r' '*.py' '*.md' '*.yml' '*.yaml' '*.ps1' \
    ':(exclude)AGENTS.md' ':(exclude)CLAUDE.md' ':(exclude)CONTRIBUTING.md' \
    ':(exclude)README.md' ':(exclude).github/**' ':(exclude)tools/check-attribution.sh' \
    2>/dev/null | grep '^+' | grep -v '^+++' || true)
  if [ -n "$ADDED" ] && printf '%s' "$ADDED" | scrub | grep -Eiq "$PATTERN"; then
    echo "Offending added lines:"
    printf '%s' "$ADDED" | scrub | grep -Ein "$PATTERN" | head -20
    report "A line added here credits an AI tool. Remove the reference."
  fi
fi

if [ ! -t 0 ]; then
  PIPED=$(cat)
  if [ -n "$PIPED" ] && printf '%s' "$PIPED" | scrub | grep -Eiq "$PATTERN"; then
    report "The pull request title or body credits an AI tool. Edit the pull request text."
  fi
fi

if [ "$fail" -eq 1 ]; then
  echo ""
  echo "See section 1 of AGENTS.md. The history of this repository must read as the work of its human authors."
  exit 1
fi

echo "Clean: no AI attribution found."
